const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--autoplay-policy=user-gesture-required'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push('dashboard: ' + e.message));
  await page.goto('http://127.0.0.1:8768/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(2500);
  const hidden = await page.$$eval('.research-only', els => els.filter(e => e.hidden).length + '/' + els.length);
  const before = await page.evaluate(() => WinSound.isUnlocked());
  await page.click('#win-sound-enable');
  await page.waitForTimeout(2500);
  const after = await page.evaluate(() => WinSound.isUnlocked());
  const label = await page.textContent('#win-sound-enable');
  await page.click('#win-video-test');
  await page.waitForTimeout(800);
  const overlay = await page.evaluate(() => !document.getElementById('win-overlay').hidden);
  const note = await page.textContent('#win-note');
  console.log(JSON.stringify({ research_hidden: hidden, unlocked_before_click: before, unlocked_after_click: after, button: label, win_overlay_shown: overlay, note }));
  const phone = await browser.newPage();
  phone.on('pageerror', e => errors.push('phone: ' + e.message));
  await phone.goto('http://127.0.0.1:8768/remote', { waitUntil: 'networkidle' });
  await phone.waitForTimeout(1500);
  await phone.click('#r-sound');
  await phone.waitForTimeout(2500);
  const p = await phone.evaluate(() => WinSound.isUnlocked());
  await phone.click('#r-sound-test');
  await phone.waitForTimeout(800);
  const banner = await phone.textContent('#win-banner');
  console.log(JSON.stringify({ phone_unlocked: p, phone_banner: banner, page_errors: errors }));
  await browser.close();
})();
